"""Dynamic server-backed CLI commands, built at runtime from the Java routes manifest.

The manifest (``automation_routes.json``, regenerated by the Maven build) is the single source of
truth: the Java side owns every route's command name, flag names, parameter types, defaults, and
description. This module reads those verbatim and builds argparse subcommands — it contains no
knowledge of any specific route.
"""

from .cli_registry import CliCommandResult


_PARAM_PY_TYPE = {"int": int, "float": float, "string": str}


def server_command_map(manifest: dict) -> dict:
    """Map each server route to its Java-declared command name.

    A registry command never takes a route's name (``test_cli`` holds the two sets disjoint), so
    no route is shadowed here.

    :param manifest: parsed routes manifest
    :return: ordered mapping of command name to route dict
    """
    routes = sorted(manifest.get("routes", []), key=lambda route: route["commandName"])
    return {route["commandName"]: route for route in routes}


def add_server_parsers(subparsers, command_map: dict) -> None:
    """Add one argparse subparser per dynamic server route.

    A route whose Java-declared command name carries a space (``"rings add"``) becomes a group
    subcommand: ``ixdar-cli rings add``. Every leaf parser records its own full name under
    ``resolved_command`` so dispatch never has to re-join the words.

    :param subparsers: the argparse subparsers action to add to
    :param command_map: name-to-route mapping from :func:`server_command_map`
    """
    groups: dict = {}
    for name, route in command_map.items():
        if " " in name:
            group_name, leaf_name = name.split(" ", 1)
            if group_name not in groups:
                group_parser = subparsers.add_parser(group_name, help=f"{group_name} commands")
                groups[group_name] = group_parser.add_subparsers(
                    dest=f"{group_name}_subcommand", required=True
                )
            parser = groups[group_name].add_parser(leaf_name, help=route.get("description", ""))
        else:
            parser = subparsers.add_parser(name, help=route.get("description", ""))
        parser.set_defaults(resolved_command=name)
        for param in route.get("params", []):
            _add_param_argument(parser, param)


def _add_param_argument(parser, param: dict) -> None:
    flag = f"--{param['cliName'].replace('_', '-')}"
    dest = param["name"]
    example = param.get("example", "")
    help_text = param.get("help", "")
    if example:
        help_text = f"{help_text} (e.g. {example})".strip()
    param_type = param.get("type", "string")

    if param.get("positional", False):
        if param.get("required", True):
            parser.add_argument(dest, type=_PARAM_PY_TYPE.get(param_type, str), help=help_text)
        else:
            parser.add_argument(
                dest,
                nargs="?",
                type=_PARAM_PY_TYPE.get(param_type, str),
                default=_coerce_default(param_type, param.get("default", "")),
                help=help_text,
            )
        return

    if param_type == "string_list":
        parser.add_argument(flag, dest=dest, action="append", default=[], help=f"{help_text} Repeatable.")
        return

    if param_type == "bool":
        default = str(param.get("default", "")).lower() == "true"
        parser.add_argument(
            flag,
            dest=dest,
            action="store_false" if default else "store_true",
            default=default,
            help=help_text,
        )
        return

    kwargs = {"dest": dest, "type": _PARAM_PY_TYPE.get(param_type, str), "help": help_text}
    if param.get("required", False):
        kwargs["required"] = True
    else:
        kwargs["default"] = _coerce_default(param_type, param.get("default", ""))
    parser.add_argument(flag, **kwargs)


def _coerce_default(param_type: str, raw: str):
    if param_type == "int":
        return int(raw) if str(raw).strip() != "" else None
    if param_type == "float":
        return float(raw) if str(raw).strip() != "" else None
    return raw


def dispatch_server_command(route: dict, args, client) -> CliCommandResult:
    """Call the automation server for a dynamic route, returning its JSON response.

    :param route: the route dict resolved from the manifest
    :param args: parsed argparse namespace
    :param client: an ``AutomationClient``
    :return: the server response wrapped in a ``CliCommandResult``, exiting non-zero when the
        response says ``"ok": false``
    """
    body = {param["name"]: getattr(args, param["name"]) for param in route.get("params", [])}
    payload = client.call(route["commandName"], **body)
    return CliCommandResult(payload=payload, exit_code=1 if payload.get("ok") is False else 0)
